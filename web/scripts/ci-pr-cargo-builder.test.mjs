test("helper accepts only exact canonical identities and side-effect-free invalid build probes", async () => {
  const request = canonicalJson({
    baseHead,
    mergeHead,
    number: 17,
    pullRequestHead,
    version: 1,
  });
  assert.deepEqual(parseBuildRequest(Buffer.from(request)), {
    type: "pull_request",
    version: 1,
    number: 17,
    baseHead,
    pullRequestHead,
    mergeHead,
  });
  assert.throws(
    () => parseBuildRequest(Buffer.from(request + "\n")),
    /canonical JSON/,
  );
  assert.throws(
    () => parseBuildRequest(Buffer.from(JSON.stringify({
      version: 1,
      number: 17,
      baseHead,
      pullRequestHead,
      mergeHead,
    }))),
    /canonical JSON/,
  );
  const invalid = await run(process.execPath, [helperPath, "--build"], {
    PATH: "/usr/bin:/bin",
    LANG: "C.UTF-8",
  }, Buffer.alloc(0));
  assert.equal(invalid.code, 65);
  assert.equal(invalid.stdout.length, 0);
  assert.match(invalid.stderr.toString(), /^Cargo preparation helper failed:/);
  const extra = await run(process.execPath, [helperPath, "--build", "extra"], {
    PATH: "/usr/bin:/bin",
    LANG: "C.UTF-8",
  }, Buffer.alloc(0));
  assert.equal(extra.code, 65);
  assert.equal(extra.stdout.length, 0);
});

