test("Cargo resolution accepts only one fixed root-owned real trust chain", async () => {
  const cargo = "/Library/PrivilegedHelperTools/dev.nanocodex.ci-cargo";
  const visited = [];
  const identities = new Map([
    [cargo, fakeIdentity({ file: true, mode: 0o100755, nlink: 1 })],
    ["/Library/PrivilegedHelperTools", fakeIdentity({ mode: 0o40755 })],
    ["/Library", fakeIdentity({ mode: 0o40755 })],
    ["/", fakeIdentity({ mode: 0o40755 })],
  ]);
  const options = {
    realpathPath: async (path) => path,
    lstatPath: async (path) => {
      visited.push(path);
      return identities.get(path);
    },
  };
  assert.equal(await resolveFixedCargoExecutable(options), cargo);
  assert.deepEqual(visited, [cargo, "/Library/PrivilegedHelperTools", "/Library", "/"]);

  for (const [path, identity, pattern] of [
    [cargo, fakeIdentity({ file: true, uid: 501, mode: 0o100755, nlink: 1 }), /root-owned/],
    [cargo, fakeIdentity({ file: true, mode: 0o100755, nlink: 2 }), /singly-linked/],
    ["/Library", fakeIdentity({ mode: 0o40775 }), /parent/],
  ]) {
    const unsafe = new Map(identities);
    unsafe.set(path, identity);
    await assert.rejects(
      resolveFixedCargoExecutable({
        realpathPath: async (value) => value,
        lstatPath: async (value) => unsafe.get(value),
      }),
      pattern,
    );
  }
  await assert.rejects(
    resolveFixedCargoExecutable({
      realpathPath: async () => "/private/var/linked-cargo",
      lstatPath: async (path) => identities.get(path),
    }),
    /must not traverse symbolic links/,
  );
  const source = await readFile(helperPath, "utf8");
  assert.doesNotMatch(source, /\/usr\/local\/bin\/cargo|\/opt\/homebrew\/bin\/cargo|\/usr\/bin\/cargo/);
});

test("Cargo config boundary rejects content, mode, add/remove, and symlink changes", () => {
  const unchanged = new Map([
    [".cargo", `040000 tree ${"a".repeat(40)}`],
    [".cargo/config.toml", `100644 blob ${"b".repeat(40)}`],
  ]);
  assert.equal(cargoConfigurationDifference(unchanged, new Map(unchanged)), null);
  for (const changed of [
    new Map([[".cargo/config.toml", `100644 blob ${"c".repeat(40)}`]]),
    new Map([[".cargo/config.toml", `100755 blob ${"b".repeat(40)}`]]),
    new Map(),
    new Map([[".cargo/config.toml", `120000 blob ${"b".repeat(40)}`]]),
  ]) {
    assert.equal(
      cargoConfigurationDifference(unchanged, changed),
      ".cargo/config.toml",
    );
  }
  assert.equal(
    cargoConfigurationDifference(
      new Map(),
      new Map([[".cargo/config", `100644 blob ${"d".repeat(40)}`]]),
    ),
    ".cargo/config",
  );
});

test("moved deterministic vendor builder binds every locked package and one exact frame", async () => {
  const directory = await mkdtemp(resolve(tmpdir(), "nanocodex-helper-bundle-"));
  try {
    const vendor = resolve(directory, "vendor");
    await writePackage(vendor, "gitdep-1.2.3", null, {
      "Cargo.toml": "[package]\nname='gitdep'\nversion='1.2.3'\n",
      "src/lib.rs": "pub fn git_dependency() {}\n",
    });
    await writePackage(vendor, "registry-9.8.7", "b".repeat(64), {
      "Cargo.toml": "[package]\nname='registry'\nversion='9.8.7'\n",
    });
    const directories = await selectVendorDirectories(vendor, cargoLock);
    assert.deepEqual(directories, ["gitdep-1.2.3", "registry-9.8.7"]);
    const config = cargoSourceConfig(vendorOutput, cargoLock);
    assert.match(config, /directory = "\/workspace\/\.cargo-home\/vendor"/);
    const one = resolve(directory, "one.tar.gz");
    const two = resolve(directory, "two.tar.gz");
    await buildCargoVendorBundle({
      bundlePath: one,
      config,
      directories,
      vendorDirectory: vendor,
    });
    await buildCargoVendorBundle({
      bundlePath: two,
      config,
      directories,
      vendorDirectory: vendor,
    });
    assert.deepEqual(await readFile(one), await readFile(two));
    const bytes = await readFile(one);
    const descriptor = {
      version: 1,
      number: 17,
      baseHead,
      pullRequestHead,
      mergeHead,
      cargoLockBlob: "4".repeat(40),
      key: `cargo-vendor/${"4".repeat(40)}/${sha256(bytes)}/bundle.tar.gz`,
      size: bytes.length,
      sha256: sha256(bytes),
    };
    const frame = Buffer.concat([encodeFrameHeader(descriptor), bytes]);
    assert.equal(frame.length, encodeFrameHeader(descriptor).length + descriptor.size);
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
});

test("generated bundle is hashed and framed from one no-follow fd and detects path replacement", async () => {
  const directory = await mkdtemp(resolve(tmpdir(), "nanocodex-helper-fd-"));
  const bundlePath = resolve(directory, "bundle.tar.gz");
  const replacementPath = resolve(directory, "replacement.tar.gz");
  const movedPath = resolve(directory, "original-moved.tar.gz");
  const bytes = Buffer.from("fixed generated Cargo vendor bytes");
  let bundle;
  try {
    await writeFile(bundlePath, bytes, { mode: 0o600 });
    await chmod(bundlePath, 0o600);
    bundle = await openGeneratedBundle(bundlePath);
    const descriptor = {
      version: 1,
      head: "5".repeat(40),
      cargoLockBlob: "4".repeat(40),
      key: `cargo-vendor/${"4".repeat(40)}/${sha256(bytes)}/bundle.tar.gz`,
      size: bytes.length,
      sha256: sha256(bytes),
    };
    const output = [];
    await writeCargoVendorFrame({ write: (chunk) => (output.push(Buffer.from(chunk)), true) }, descriptor, bundle);
    assert.deepEqual(Buffer.concat(output), Buffer.concat([encodeFrameHeader(descriptor), bytes]));

    await bundle.handle.close();
    bundle = await openGeneratedBundle(bundlePath);
    await writeFile(replacementPath, Buffer.from(bytes), { mode: 0o600 });
    await chmod(replacementPath, 0o600);
    let replaced = false;
    await assert.rejects(
      writeCargoVendorFrame({
        write(chunk) {
          if (!replaced) {
            replaced = true;
            renameSync(bundlePath, movedPath);
            renameSync(replacementPath, bundlePath);
          }
          return true;
        },
      }, descriptor, bundle),
      /bundle (?:has an unsafe identity|changed while framing|path changed)/,
    );
    const linkPath = resolve(directory, "bundle-link.tar.gz");
    await symlink(bundlePath, linkPath);
    await assert.rejects(openGeneratedBundle(linkPath), /ELOOP|symbolic link/i);
  } finally {
    await bundle?.handle.close().catch(() => undefined);
    await rm(directory, { recursive: true, force: true });
  }
});

test("builder rejects successful tool leader exit with a TERM-ignoring detached-stdio descendant", {
  timeout: 10_000,
}, async () => {
  if (process.platform === "win32") return;
  const directory = await mkdtemp(resolve(tmpdir(), "nanocodex-builder-success-group-"));
  const pidPath = resolve(directory, "processes.json");
  const controller = new AbortController();
  let processes;
  let running;
  try {
    running = runTool(process.execPath, [
      "--eval",
      leaderWithTermIgnoringDescendant(pidPath),
    ], {
      cwd: directory,
      env: { LANG: "C.UTF-8", PATH: process.env.PATH ?? "/usr/bin:/bin" },
      signal: controller.signal,
      operation: "builder success fixture",
    });
    processes = await waitForProcessFixture(pidPath);
    await waitForProcessGone(processes.leader);
    assertProcessAlive(processes.descendant);
    await assert.rejects(
      running.catch((cause) => {
        assertProcessDead(processes.descendant);
        throw cause;
      }),
      /left a live detached process-group descendant/,
    );
    await waitForProcessGone(processes.descendant);
  } finally {
    controller.abort(new DOMException("test cleanup", "AbortError"));
    await running?.catch(() => undefined);
    forceKillProcess(processes?.leader);
    forceKillProcess(processes?.descendant);
    await rm(directory, { recursive: true, force: true });
  }
});

test("builder abort after tool leader exit wins and awaits descendant group cleanup", {
  timeout: 10_000,
}, async () => {
  if (process.platform === "win32") return;
  const directory = await mkdtemp(resolve(tmpdir(), "nanocodex-builder-exit-abort-"));
  const pidPath = resolve(directory, "processes.json");
  const controller = new AbortController();
  let processes;
  let running;
  try {
    running = runTool(process.execPath, [
      "--eval",
      leaderWithTermIgnoringDescendant(pidPath),
    ], {
      cwd: directory,
      env: { LANG: "C.UTF-8", PATH: process.env.PATH ?? "/usr/bin:/bin" },
      signal: controller.signal,
      operation: "builder abort fixture",
    });
    processes = await waitForProcessFixture(pidPath);
    await waitForProcessGone(processes.leader);
    assertProcessAlive(processes.descendant);
    controller.abort(new DOMException("builder superseded after leader exit", "AbortError"));
    await assert.rejects(
      running.catch((cause) => {
        assertProcessDead(processes.descendant);
        throw cause;
      }),
      (cause) =>
        cause?.name === "AbortError" &&
        cause.message === "builder superseded after leader exit",
    );
    await waitForProcessGone(processes.descendant);
  } finally {
    controller.abort(new DOMException("test cleanup", "AbortError"));
    await running?.catch(() => undefined);
    forceKillProcess(processes?.leader);
    forceKillProcess(processes?.descendant);
    await rm(directory, { recursive: true, force: true });
  }
});

